import { writeFileSync } from "fs";
import { basename, resolve } from "path";
import chalk from "chalk";
import ora from "ora";
import boxen from "boxen";
import { analyzeStructure } from "./analyzers/structure.js";
import { analyzeDependencies } from "./analyzers/dependencies.js";
import { analyzeGitHistory } from "./analyzers/git.js";
import { analyzeTypeScript } from "./analyzers/typescript.js";
import { analyzeRoutes } from "./analyzers/routes.js";
import { analyzeConfig } from "./analyzers/config.js";

export interface GeneratorOptions {
  outputFile: string;
  verbose: boolean;
  analyzeGit: boolean;
  analyzeTypes: boolean;
  maxDepth: number;
}

interface AnalysisResult {
  section: string;
  content: string;
  itemCount: number;
}

async function runAnalyzer(
  name: string,
  fn: () => Promise<AnalysisResult>,
  verbose: boolean
): Promise<AnalysisResult | null> {
  const spinner = ora({ text: chalk.cyan(name), indent: 2 }).start();
  try {
    const result = await fn();
    spinner.succeed(
      chalk.green(`${name}`) +
        chalk.gray(` (${result.itemCount} items)`)
    );
    return result;
  } catch (err) {
    spinner.warn(chalk.yellow(`${name} — skipped (${(err as Error).message})`));
    return null;
  }
}

export async function generateContext(
  targetDir: string,
  options: GeneratorOptions
): Promise<void> {
  const projectName = basename(targetDir);
  const startTime = Date.now();

  console.log(
    chalk.bold.white(`\n  📂 Analyzing: `) +
      chalk.cyan(targetDir) +
      "\n"
  );

  const results: AnalysisResult[] = [];

  // Run all analyzers
  const structureResult = await runAnalyzer(
    "File structure & organization",
    () => analyzeStructure(targetDir, options.maxDepth),
    options.verbose
  );
  if (structureResult) results.push(structureResult);

  const depsResult = await runAnalyzer(
    "Dependencies & package info",
    () => analyzeDependencies(targetDir),
    options.verbose
  );
  if (depsResult) results.push(depsResult);

  const configResult = await runAnalyzer(
    "Configuration files",
    () => analyzeConfig(targetDir),
    options.verbose
  );
  if (configResult) results.push(configResult);

  if (options.analyzeTypes) {
    const tsResult = await runAnalyzer(
      "TypeScript exports & types",
      () => analyzeTypeScript(targetDir),
      options.verbose
    );
    if (tsResult) results.push(tsResult);
  }

  const routesResult = await runAnalyzer(
    "API routes & endpoints",
    () => analyzeRoutes(targetDir),
    options.verbose
  );
  if (routesResult) results.push(routesResult);

  if (options.analyzeGit) {
    const gitResult = await runAnalyzer(
      "Git history & contributors",
      () => analyzeGitHistory(targetDir),
      options.verbose
    );
    if (gitResult) results.push(gitResult);
  }

  // Assemble the context file
  const elapsed = ((Date.now() - startTime) / 1000).toFixed(1);
  const totalItems = results.reduce((sum, r) => sum + r.itemCount, 0);

  let markdown = `# 🧠 Codebase Context: ${projectName}\n\n`;
  markdown += `> Auto-generated by [codebase-context-gen](https://github.com/tanwigeetika1618/codebase-context-gen)\n`;
  markdown += `> Generated: ${new Date().toISOString().split("T")[0]}\n`;
  markdown += `> This file helps AI agents understand your codebase without reading every file.\n`;
  markdown += `> Feed this to Claude, Cursor, Codex, or any AI tool as context.\n\n`;
  markdown += `---\n\n`;

  for (const result of results) {
    markdown += result.content + "\n\n";
  }

  markdown += `---\n\n`;
  markdown += `## 📌 How to Use This File\n\n`;
  markdown += `Paste or attach this file when starting a conversation with any AI coding assistant:\n\n`;
  markdown += `- **Cursor**: Drop it in the chat or add to context with @file\n`;
  markdown += `- **Claude CLI**: \`cat .ai-context.md | claude "explain this codebase"\`\n`;
  markdown += `- **Codex**: Include in your prompt as context\n`;
  markdown += `- **ChatGPT**: Paste in the conversation\n\n`;
  markdown += `This saves thousands of tokens by giving the AI a map instead of making it explore blindly.\n`;

  // Write the file
  const outputPath = resolve(targetDir, options.outputFile);
  writeFileSync(outputPath, markdown, "utf-8");

  const fileSize = (Buffer.byteLength(markdown, "utf-8") / 1024).toFixed(1);
  const tokenEstimate = Math.round(markdown.length / 4);

  console.log(
    boxen(
      chalk.bold.green("✅ Context file generated!\n\n") +
        chalk.white(`  📄 File:     `) + chalk.cyan(options.outputFile) + "\n" +
        chalk.white(`  📊 Size:     `) + chalk.yellow(`${fileSize} KB`) + chalk.gray(` (~${tokenEstimate} tokens)`) + "\n" +
        chalk.white(`  🔍 Analyzed: `) + chalk.yellow(`${totalItems} items`) + chalk.gray(` across ${results.length} analyzers`) + "\n" +
        chalk.white(`  ⏱️  Time:     `) + chalk.yellow(`${elapsed}s`) + "\n\n" +
        chalk.gray(`  Compared to an AI agent exploring the codebase (~50,000+ tokens),\n`) +
        chalk.gray(`  this context file uses `) + chalk.bold.green(`~${tokenEstimate} tokens`) + chalk.gray(` — a `) +
        chalk.bold.green(`${Math.round(50000 / tokenEstimate)}x`) + chalk.gray(` reduction.`),
      {
        padding: 1,
        margin: { top: 1, bottom: 1, left: 2, right: 2 },
        borderStyle: "round",
        borderColor: "green",
        title: "🧠 codebase-context-gen",
        titleAlignment: "center",
      }
    )
  );
}
